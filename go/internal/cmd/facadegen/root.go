// Existing semantic component names remain stable. Explicit names also keep
// each compatibility type paired with its compatibility constructor.
var rootWidgetNames = map[string]string{
	"Button": "WidgetButton", "NewButton": "NewWidgetButton",
	"Form": "WidgetForm", "NewForm": "NewWidgetForm",
	"Grid": "WidgetGrid", "NewGrid": "NewWidgetGrid",
	"List": "WidgetList", "NewList": "NewWidgetList",
	"TextView": "WidgetTextView", "NewTextView": "NewWidgetTextView",
	"TreeView": "WidgetTreeView", "NewTreeView": "NewWidgetTreeView",
	"TreeNode": "WidgetTreeNode", "NewTreeNode": "NewWidgetTreeNode",
	"Styles": "WidgetStyles", "GetStyles": "GetWidgetStyles", "SetStyles": "SetWidgetStyles",
	"Theme": "WidgetTheme",
}

type rootDecl struct {
	name, kind, pkg string
	fn              *ast.FuncDecl
}

func packageDecls(dir string) []rootDecl {
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	must(err)
	var result []rootDecl
	for _, file := range files {
		if strings.HasSuffix(file, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), file, nil, 0)
		must(err)
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil && d.Name.IsExported() {
					result = append(result, rootDecl{name: d.Name.Name, kind: "func", fn: d})
				}
			case *ast.GenDecl:
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.TypeSpec:
						if s.Name.IsExported() {
							result = append(result, rootDecl{name: s.Name.Name, kind: "type"})
						}
					case *ast.ValueSpec:
						for _, name := range s.Names {
							if name.IsExported() {
								result = append(result, rootDecl{name: name.Name, kind: d.Tok.String()})
							}
						}
					}
				}
			}
		}
	}
	return result
}

func rootName(pkg, name string) string {
	if pkg == "ui" {
		if renamed, ok := rootWidgetNames[name]; ok {
			return renamed
		}
	}
	return name
}

// generateRoot keeps the one-import API complete, including callbacks and
// inherited backend methods. It does not modify the compatibility subpackages.
func generateRoot(check bool) map[string]string {
	names := map[string]bool{}
	files, err := filepath.Glob("*.go")
	must(err)
	for _, file := range files {
		if file == "facade_generated.go" || file == "facade_unix.go" || strings.HasSuffix(file, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), file, nil, 0)
		must(err)
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil && d.Name.IsExported() {
					names[d.Name.Name] = true
				}
			case *ast.GenDecl:
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.TypeSpec:
						if s.Name.IsExported() {
							names[s.Name.Name] = true
						}
					case *ast.ValueSpec:
						for _, n := range s.Names {
							if n.IsExported() {
								names[n.Name] = true
							}
						}
					}
				}
			}
		}
	}
	var all []rootDecl
	mapping := map[string]string{}
	for _, pkg := range []string{"ui", "terminal"} {
		for _, d := range packageDecls(pkg) {
			d.pkg = pkg
			name := rootName(pkg, d.name)
			if names[name] {
				panic("review root facade name collision: " + pkg + "." + d.name + " -> " + name)
			}
			names[name] = true
			mapping["github.com/leechis7/tuivory/go/"+pkg+"."+d.name] = "github.com/leechis7/tuivory/go." + name
			all = append(all, d)
		}
	}
	sort.Slice(all, func(i, j int) bool { return rootName(all[i].pkg, all[i].name) < rootName(all[j].pkg, all[j].name) })
	var out strings.Builder
	out.WriteString("// Code generated by go run ./internal/cmd/facadegen; DO NOT EDIT.\npackage tuivory\n\nimport (\ncompatui \"github.com/leechis7/tuivory/go/ui\"\ncompatterminal \"github.com/leechis7/tuivory/go/terminal\"\nic \"image/color\"\n\"io\"\n\"time\"\n)\n\n")
	for _, d := range all {
		if d.name == "NewDevTtyFromDev" {
			continue
		}
		name := rootName(d.pkg, d.name)
		target := "compat" + d.pkg + "." + d.name
		switch d.kind {
		case "type":
			fmt.Fprintf(&out, "// %s preserves the compatibility type and its methods.\ntype %s = %s\n\n", name, name, target)
		case "const":
			fmt.Fprintf(&out, "const %s = %s\n\n", name, target)
		case "var":
			fmt.Fprintf(&out, "// %s is a startup value (maps share entries). Use configuration setters for backend globals.\nvar %s = %s\n\n", name, name, target)
		case "func":
			args := []string{}
			for _, p := range d.fn.Type.Params.List {
				for _, n := range p.Names {
					args = append(args, n.Name)
				}
			}
			if n := len(d.fn.Type.Params.List); n > 0 {
				if _, ok := d.fn.Type.Params.List[n-1].Type.(*ast.Ellipsis); ok {
					args[len(args)-1] += "..."
				}
			}
			// Go signatures refer to local types or SDK terminal aliases. Qualify only
			// type identifiers; argument names and standard library selectors stay intact.
			sig := rewriteRootSignature(d.fn.Type, d.pkg)
			call := target + "(" + strings.Join(args, ",") + ")"
			if d.fn.Type.Results != nil && len(d.fn.Type.Results.List) > 0 {
				call = "return " + call
			}
			if d.pkg == "ui" && d.name == "SetSemigraphicJoints" {
				call += "; SemigraphicJoints = compatui.SemigraphicJoints"
			}
			fmt.Fprintf(&out, "// %s forwards to the SDK compatibility API.\nfunc %s%s { %s }\n\n", name, name, sig, call)
		}
	}
	formatted, err := format.Source([]byte(out.String()))
	must(err)
	write("facade_generated.go", formatted, check)
	unix := "// Code generated by go run ./internal/cmd/facadegen; DO NOT EDIT.\n//go:build aix || darwin || dragonfly || freebsd || linux || netbsd || openbsd || solaris || zos\n\npackage tuivory\n\nimport compatterminal \"github.com/leechis7/tuivory/go/terminal\"\n\n// NewDevTtyFromDev preserves Unix-only terminal device selection.\nfunc NewDevTtyFromDev(device string) (Tty,error) { return compatterminal.NewDevTtyFromDev(device) }\n"
	formatted, err = format.Source([]byte(unix))
	must(err)
	write("facade_unix.go", formatted, check)
	return mapping
}

func rewriteRootSignature(fn *ast.FuncType, pkg string) string {
	var rewrite func(ast.Expr) ast.Expr
	rewrite = func(expr ast.Expr) ast.Expr {
		switch x := expr.(type) {
		case *ast.Ident:
			if ast.IsExported(x.Name) {
				x.Name = rootName(pkg, x.Name)
			}
		case *ast.SelectorExpr:
			if id, ok := x.X.(*ast.Ident); ok && (id.Name == "encoding" || id.Name == "terminfo") {
				return ast.NewIdent(x.Sel.Name)
			}
			if id, ok := x.X.(*ast.Ident); ok && (id.Name == "tcell" || id.Name == "native") {
				from := pkg
				if id.Name == "tcell" {
					from = "terminal"
				}
				return ast.NewIdent(rootName(from, x.Sel.Name))
			}
		case *ast.StarExpr:
			x.X = rewrite(x.X)
		case *ast.ArrayType:
			x.Elt = rewrite(x.Elt)
		case *ast.MapType:
			x.Key = rewrite(x.Key)
			x.Value = rewrite(x.Value)
		case *ast.Ellipsis:
			x.Elt = rewrite(x.Elt)
		case *ast.FuncType:
			fields(x.Params, rewrite)
			fields(x.Results, rewrite)
		case *ast.ChanType:
			x.Value = rewrite(x.Value)
		case *ast.InterfaceType:
			fields(x.Methods, rewrite)
		case *ast.StructType:
			fields(x.Fields, rewrite)
		}
		return expr
	}
	fields(fn.Params, rewrite)
	fields(fn.Results, rewrite)
	return strings.TrimPrefix(printed(fn), "func")
}
func fields(list *ast.FieldList, rewrite func(ast.Expr) ast.Expr) {
	if list != nil {
		for _, f := range list.List {
			f.Type = rewrite(f.Type)
		}
	}
}
